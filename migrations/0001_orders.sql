-- The orders table: one real, typed column for each field of the old app's All Orders sheet (generated from its column list).
-- Blank in the sheet is NULL; a checkbox is 1 / 0 / NULL; dates are real dates.
CREATE TABLE orders (
  `rn` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `label_number` VARCHAR(255) NULL,
  `gift_note` TEXT NULL,
  `store_order_no` VARCHAR(255) NULL,
  `product_name` TEXT NULL,
  `brand` VARCHAR(255) NULL,
  `qty` INT NULL,
  `customer_name` VARCHAR(255) NULL,
  `address` TEXT NULL,
  `source_order_date` DATE NULL,
  `source_order_number` VARCHAR(255) NULL,
  `source_tracking_number` TEXT NULL,
  `shipping_label_link` TEXT NULL,
  `product_image_link` TEXT NULL,
  `source_order_status` VARCHAR(255) NULL,
  `package_not_received` TINYINT(1) NULL,
  `to_void` TINYINT(1) NULL,
  `item_on_hold` TINYINT(1) NULL,
  `stock` TINYINT(1) NULL,
  `label_used` TINYINT(1) NULL,
  `shipped_to_customer` TINYINT(1) NULL,
  `shipped_to_amazon` TINYINT(1) NULL,
  `label_voided` TINYINT(1) NULL,
  `tracking_number_to_customer` VARCHAR(255) NULL,
  `delivery_date` DATE NULL,
  `tracking_status` VARCHAR(255) NULL,
  `notes` TEXT NULL,
  `store` VARCHAR(255) NULL,
  `ph_team_internal_notes` TEXT NULL,
  `days_in_transit` VARCHAR(255) NULL,
  `number_of_orders` INT NULL,
  `print_link` TEXT NULL,
  `softr_record_id` VARCHAR(255) NULL,
  `number_of_items` INT NULL,
  `boxes_received` INT NULL,
  `boxes_expected` INT NULL,
  `hold_warning` VARCHAR(255) NULL,
  `hold_date` DATETIME NULL,
  `sku` VARCHAR(255) NULL,
  `stock_no` VARCHAR(255) NULL,
  `tapicker_status` VARCHAR(255) NULL,
  `tapicker_shipped_date` DATETIME NULL,
  `tapicker_delivery_date` DATETIME NULL,
  `label_chip` TEXT NULL,
  `shipped_to_customer_date` DATETIME NULL,
  `shipped_to_amazon_date` DATETIME NULL,
  `rts_counter` INT NULL,
  `rta_counter` INT NULL,
  `item_on_hold_counter` INT NULL,
  `store_returns_counter` INT NULL,
  `all_orders_counter` INT NULL,
  `stock_counter` INT NULL,
  `updated_by` VARCHAR(255) NULL,
  `delivered_to_warehouse_date` DATETIME NULL,
  `items_received` INT NULL,
  `search_text` MEDIUMTEXT NULL COMMENT 'lower-case text of the searchable fields, for the search box',
  `created_at` DATETIME NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`rn`),
  KEY `ix_label_number` (`label_number`),
  KEY `ix_store_order_no` (`store_order_no`),
  KEY `ix_customer_name` (`customer_name`),
  KEY `ix_source_order_date` (`source_order_date`),
  KEY `ix_source_order_number` (`source_order_number`),
  KEY `ix_source_order_status` (`source_order_status`),
  KEY `ix_package_not_received` (`package_not_received`),
  KEY `ix_to_void` (`to_void`),
  KEY `ix_item_on_hold` (`item_on_hold`),
  KEY `ix_stock` (`stock`),
  KEY `ix_shipped_to_customer` (`shipped_to_customer`),
  KEY `ix_shipped_to_amazon` (`shipped_to_amazon`),
  KEY `ix_label_voided` (`label_voided`),
  KEY `ix_tracking_number_to_customer` (`tracking_number_to_customer`),
  KEY `ix_delivery_date` (`delivery_date`),
  KEY `ix_tracking_status` (`tracking_status`),
  KEY `ix_store` (`store`),
  KEY `ix_hold_date` (`hold_date`),
  KEY `ix_stock_no` (`stock_no`),
  KEY `ix_shipped_to_customer_date` (`shipped_to_customer_date`),
  KEY `ix_shipped_to_amazon_date` (`shipped_to_amazon_date`),
  KEY `ix_updated_by` (`updated_by`),
  KEY `ix_delivered_to_warehouse_date` (`delivered_to_warehouse_date`),
  FULLTEXT KEY `ft_search` (`search_text`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
